export function attributeLabel(name: string, locale: Locale): string {
  const hit = LABELS[name];
  if (hit) return locale === 'sl' ? hit[0] : hit[1];
  const human = name.replace(/[_-]+/g, ' ').trim();
  return human.charAt(0).toUpperCase() + human.slice(1);
}
